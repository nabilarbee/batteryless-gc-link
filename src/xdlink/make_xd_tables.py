#!/usr/bin/env python3
"""Writes xd_tables.c, the list of XD link programs the link hook fixes.

usage: make_xd_tables.py OUTPUT.c PROGRAM.gba [...]

The programs come from patch_colosseum_iso.py extract on an XD disc. Only
addresses, sizes and hashes go into the output, no bytes of XD's programs.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze_xd as A                                   # noqa: E402

COLOSSEUM_PROGRAM = 0x089AA144       # Emerald (BPEE) gMultiBootProgram_PokemonColosseum
CALLS = [('identify', 'XD_CALL_IDENTIFY'), ('read', 'XD_CALL_READ'), ('verify', 'XD_CALL_VERIFY'),
         ('verifyN', 'XD_CALL_VERIFY_N'), ('savePhase', 'XD_CALL_SAVE_PHASE')]
PARAMS = ['identifyFlash', 'readFlash', 'verifyFlashSector', 'verifyFlashSectorNBytes', 'savePhase',
          'soundVSyncOff', 'soundVSyncOn']
VARS = ['programFlashByte', 'programFlashSector', 'eraseFlashChip', 'eraseFlashSector', 'waitForFlashWrite',
        'flashMaxTime', 'flash']


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    m = A.Matcher()
    entries, template = [], None
    for path in argv[2:]:
        try:
            r, prog, img = A.analyze(path, m)
        except ValueError as e:
            print('skipped %s: %s' % (os.path.basename(path), e))
            continue
        t = A.loader_template(prog, r['loaderOffset'])
        if template is None:
            template = t
        elif t != template:
            raise SystemExit('error: %s has a different loader' % path)
        sites = [(s, c) for k, c in CALLS for s in r['sites'][k]]
        if len(sites) > 8:
            raise SystemExit('error: too many call sites in %s' % path)
        entries.append((r, sites))
        print('%-32s %s, %d sites' % (r['file'], 'trade (writes)' if r['canWrite'] else 'read only', len(sites)))
    if not entries:
        raise SystemExit('error: no usable XD program')

    out = ['// Generated by make_xd_tables.py from XD\'s GBA link programs. Do not edit.',
           '#include "xd_link.h"', '',
           'const u32 gColosseumProgram = 0x%08X;' % COLOSSEUM_PROGRAM, '',
           'const struct XdProgram gXdPrograms[] =', '{']
    for r, sites in entries:
        out.append('    {   // %s' % r['file'])
        out.append('        0x%08X, 0x%X, 0x%X, 0x%X, 0x%X, 0x%08X,' % (
            r['recvHash'], r['loaderOffset'], r['blobStart'], r['blobEnd'], r['decSize'], r['decHash']))
        out.append('        %d,' % len(sites))
        out.append('        {')
        for s, c in sites:
            out.append('            {0x%08X, %s},' % (s, c))
        out.append('        },')
        vals = [r['functions'][k] for k in PARAMS] + [r['variables'][k] for k in VARS]
        out.append('        {')
        for k, v in zip(PARAMS + VARS, vals):
            out.append('            0x%08X, // %s' % (v, k))
        out.append('        },')
        out.append('    },')
    out += ['};', '', 'const u32 gNumXdPrograms = %d;' % len(entries), '']
    open(argv[1], 'w').write('\n'.join(out))
    print('wrote %s: %d programs' % (argv[1], len(entries)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
